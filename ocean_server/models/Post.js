const { DataTypes } = require('sequelize');

module.exports = (sequelize) => {
    const Post = sequelize.define('Post', {
        id: {
            type: DataTypes.UUID,
            defaultValue: DataTypes.UUIDV4,
            primaryKey: true
        },
        userId: {
            type: DataTypes.UUID,
            allowNull: false,
            references: {
                model: 'users',
                key: 'id'
            }
        },
        postType: {
            type: DataTypes.ENUM('product', 'buyer_request', 'general'),
            allowNull: false,
            defaultValue: 'product'
        },
        // Unified feed system fields
        contentType: {
            type: DataTypes.ENUM('post', 'product', 'group_buy', 'swap_deal', 'auction', 'distress_sale'),
            allowNull: false,
            defaultValue: 'post',
            field: 'content_type'
        },
        sourceId: {
            type: DataTypes.STRING(255),
            allowNull: true,
            field: 'source_id',
            comment: 'ID of the original item (product_id, group_buy_id, etc.)'
        },
        sourceTable: {
            type: DataTypes.STRING(50),
            allowNull: true,
            field: 'source_table',
            comment: 'Original table name (products, group_buys, swap_deals, etc.)'
        },
        autoGenerated: {
            type: DataTypes.BOOLEAN,
            defaultValue: false,
            field: 'auto_generated',
            comment: 'Whether this post was auto-generated from another content type'
        },
        originalCreatedAt: {
            type: DataTypes.DATE,
            allowNull: true,
            field: 'original_created_at',
            comment: 'Original creation date from source item'
        },
        feedMetadata: {
            type: DataTypes.JSON,
            allowNull: true,
            field: 'feed_metadata',
            comment: 'Additional metadata for feed display (pricing, status, etc.)'
        },
        feedVisible: {
            type: DataTypes.BOOLEAN,
            defaultValue: true,
            field: 'feed_visible',
            comment: 'Whether this post should appear in the main feed'
        },
        feedPriority: {
            type: DataTypes.INTEGER,
            defaultValue: 0,
            field: 'feed_priority',
            comment: 'Priority score for feed ordering (higher = more important)'
        },
        content: {
            type: DataTypes.TEXT,
            allowNull: false
        },
        // Product-specific fields
        productName: {
            type: DataTypes.STRING(255),
            allowNull: true
        },
        brand: {
            type: DataTypes.STRING(100),
            allowNull: true
        },
        price: {
            type: DataTypes.DECIMAL(15, 2),
            allowNull: true
        },
        currency: {
            type: DataTypes.STRING(3),
            defaultValue: 'USD'
        },
        location: {
            type: DataTypes.STRING(255),
            allowNull: true
        },
        // Region/Country for filtering
        userRegion: {
            type: DataTypes.STRING(100),
            allowNull: false
        },
        userCountry: {
            type: DataTypes.STRING(100),
            allowNull: false
        },
        // Engagement counters
        likesCount: {
            type: DataTypes.INTEGER,
            defaultValue: 0
        },
        commentsCount: {
            type: DataTypes.INTEGER,
            defaultValue: 0
        },
        sharesCount: {
            type: DataTypes.INTEGER,
            defaultValue: 0
        },
        savedCount: {
            type: DataTypes.INTEGER,
            defaultValue: 0
        },
        // Status
        status: {
            type: DataTypes.ENUM('active', 'inactive', 'deleted'),
            defaultValue: 'active'
        },
        // Tags for search
        tags: {
            type: DataTypes.JSON,
            allowNull: true
        }
    }, {
        tableName: 'posts',
        timestamps: true,
        indexes: [
            {
                fields: ['userId']
            },
            {
                fields: ['postType']
            },
            {
                fields: ['userRegion']
            },
            {
                fields: ['userCountry']
            },
            {
                fields: ['status']
            },
            {
                fields: ['createdAt']
            },
            // Unified feed system indexes
            {
                fields: ['content_type']
            },
            {
                fields: ['source_table', 'source_id']
            },
            {
                fields: ['feed_visible', 'status']
            },
            {
                fields: ['feed_priority', 'createdAt']
            },
            {
                fields: ['auto_generated']
            }
        ]
    });

    Post.associate = function(models) {
        Post.belongsTo(models.UserTable, {
            foreignKey: 'userId',
            as: 'user'
        });
        
        if (models.PostMedia) {
            Post.hasMany(models.PostMedia, {
                foreignKey: 'postId',
                as: 'media'
            });
        }
        
        if (models.PostLike) {
            Post.hasMany(models.PostLike, {
                foreignKey: 'postId',
                as: 'likes'
            });
        }
        
        if (models.PostComment) {
            Post.hasMany(models.PostComment, {
                foreignKey: 'postId',
                as: 'comments'
            });
        }
        
        if (models.PostShare) {
            Post.hasMany(models.PostShare, {
                foreignKey: 'postId',
                as: 'shares'
            });
        }
        
        if (models.SavedPost) {
            Post.hasMany(models.SavedPost, {
                foreignKey: 'postId',
                as: 'savedBy'
            });
        }
    };

    return Post;
}; 